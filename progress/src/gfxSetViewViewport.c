typedef struct { s16 x; s16 y; s16 w; s16 h; s16 vscale[4]; s16 vtrans[4]; s16 ulx; s16 uly; s16 lrx; s16 lry; u8 pad[8]; } View;
typedef struct { u8 pad[0x2110]; View view[2]; } Big;
extern Big sRowBoard;
extern u8 viewIndex;
#define V sRowBoard.view[viewIndex]

/* Sets the viewport and scissor for the current split-screen view, clamps the scissor to the screen, and emits the display-list commands. */ void gfxSetViewViewport(Gfx **gfxp) {
    V.vscale[0] = V.w * 2;
    V.vscale[1] = V.h * 2;
    V.vscale[2] = 0x1FF;
    V.vscale[3] = 0;
    V.vtrans[0] = (V.x + V.w * 0.5) * 4.0;
    V.vtrans[1] = (V.y + V.h * 0.5) * 4.0;
    V.vtrans[2] = 0x1FF;
    V.vtrans[3] = 0;
    gDPPipeSync((*gfxp)++);
    gDma((*gfxp)++, 0x03800010, V.vscale);
    if (V.ulx < 0) {
        V.ulx = 0;
    }
    if (V.lrx > 320) {
        V.ulx = 320;
    }
    if (V.ulx > V.lrx) {
        V.ulx = V.lrx;
    }
    if (V.lrx < V.ulx) {
        V.lrx = V.ulx;
    }
    if (V.uly < 0) {
        V.uly = 0;
    }
    if (V.lry > 240) {
        V.uly = 240;
    }
    if (V.uly > V.lry) {
        V.uly = V.lry;
    }
    if (V.lry < V.uly) {
        V.lry = V.uly;
    }
    gDma((*gfxp)++, _S(0xED, 24, 8) | _S((s32)((f32)V.ulx * 4.0F), 12, 12) | _S((s32)((f32)V.uly * 4.0F), 0, 12),
         _S((s32)((f32)V.lrx * 4.0F), 12, 12) | _S((s32)((f32)V.lry * 4.0F), 0, 12));
}
